# Essayons différentes substitutions pour @
content = "d0c_@yz@gl_mn0j_pm3z3_g0_o00s"

# @ = 0
print("Avec @ = 0:", content.replace("@", "0"))

# @ = o
print("Avec @ = o:", content.replace("@", "o"))

# @ = a
print("Avec @ = a:", content.replace("@", "a"))

# @ = e
print("Avec @ = e:", content.replace("@", "e"))

# @ = i
print("Avec @ = i:", content.replace("@", "i"))

# @ = u
print("Avec @ = u:", content.replace("@", "u"))